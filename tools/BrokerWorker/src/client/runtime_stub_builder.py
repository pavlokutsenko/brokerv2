def run_main_generator(
    _image: Path,
    cave: int,
    direct_hook: int,
    send: int,
    send_first_five: bytes,
) -> tuple[bytes, int]:
    if len(send_first_five) != 5:
        raise ValueError("send prologue must contain five bytes")
    result = bytearray(_MAIN)
    struct.pack_into("<Q", result, 15, cave)
    struct.pack_into("<Q", result, 597, direct_hook + 19)
    result[605:610] = send_first_five
    struct.pack_into("<Q", result, 616, send + 5)
    return bytes(result), 605


def run_post_generator(_image: Path, cave: int, post_hook: int) -> bytes:
    result = bytearray(_POST)
    struct.pack_into("<Q", result, 23, cave + 0xD00)
    struct.pack_into("<Q", result, 43, cave + 0xD38)
    struct.pack_into("<Q", result, 56, cave + 0xD00)
    struct.pack_into("<Q", result, 107, post_hook + 15)
    struct.pack_into("<Q", result, 121, post_hook + 41)
    return bytes(result)
